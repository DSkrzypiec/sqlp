package corpus

import "slices"

// ANSICase is one statement exercising a SQL standard feature. Dialects lists
// where the real engines accept it, checked by tools/corpusgen -ansi rather
// than written by hand. Feature IDs come from testdata/ansi/sql_features.txt.
type ANSICase struct {
	Feature  string
	SQL      string
	Dialects []string
}

// ANSIDialects are the dialects whose verdicts the table's labels hold.
// BigQuery's are frozen by tools/corpusgen -bigquery in
// testdata/corpus/bigquery/ansi.jsonl instead, with the other BigQuery verdicts.
var ANSIDialects = []string{"postgres", "sqlite"}

// Accepted reports whether the named dialect's engine accepts the statement.
func (c ANSICase) Accepted(dialect string) bool { return slices.Contains(c.Dialects, dialect) }

var (
	both         = []string{"postgres", "sqlite"}
	postgresOnly = []string{"postgres"}
	sqliteOnly   = []string{"sqlite"}
	neither      = []string{}
)

// DialectsLabel names a dialect list as written in the ANSI table.
func DialectsLabel(postgres, sqlite bool) string {
	switch {
	case postgres && sqlite:
		return "both"
	case postgres:
		return "postgresOnly"
	case sqlite:
		return "sqliteOnly"
	}
	return "neither"
}

