// A statement that fails must report a useful position.
func TestErrorHasPosition(t *testing.T) {
	testkit.Require(t, dialect.Postgres.Name)
	_, err := Parse("SELECT a FROM t WHERE a = = 1", dialect.Postgres)
	if err == nil {
		t.Fatal("expected error")
	}
	if want := "line 1, column 27"; !strings.Contains(err.Error(), want) {
		t.Fatalf("error %q should mention %q", err.Error(), want)
	}
}
